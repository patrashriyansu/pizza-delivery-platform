import 'dotenv/config';
import http from 'node:http';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import {Server} from 'socket.io';
import jwt from 'jsonwebtoken';
import {connectDB} from './config/db.js';
import User from './models/User.js';
import authRoutes from './routes/auth.js';
import pizzaRoutes from './routes/pizzas.js';
import orderRoutes from './routes/orders.js';
import adminRoutes from './routes/admin.js';
import {startLowStockJob} from './jobs/lowStock.js';
const app=express(); const server=http.createServer(app);
const origins=(process.env.CORS_ORIGINS||process.env.CLIENT_URL||'http://localhost:5173').split(',').map(x=>x.trim());
const io=new Server(server,{cors:{origin:origins,methods:['GET','POST','PATCH']}}); app.set('io',io);
io.use(async(socket,next)=>{try{const token=socket.handshake.auth?.token; if(!token) return next(new Error('Unauthorized')); const decoded=jwt.verify(token,process.env.JWT_SECRET); const user=await User.findById(decoded.sub); if(!user) return next(new Error('Unauthorized')); socket.userId=user._id.toString(); next();}catch{next(new Error('Unauthorized'));}});
io.on('connection',socket=>socket.join(`user:${socket.userId}`));
app.use(helmet()); app.use(cors({origin:(origin,cb)=>!origin||origins.includes(origin)?cb(null,true):cb(new Error('Origin not allowed'))})); app.use(express.json({limit:'1mb'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,max:30,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.use('/api/pizzas',pizzaRoutes); app.use('/api/orders',orderRoutes); app.use('/api/admin',adminRoutes);
app.get('/api/health',(req,res)=>res.json({status:'ok'}));
app.use((err,req,res,next)=>{console.error(err); const status=err.status|| (err.name==='ValidationError'?400:500); res.status(status).json({message:status===500?'Something went wrong. Please try again.':err.message});});
const port=Number(process.env.PORT||5000);
connectDB(process.env.MONGO_URI).then(()=>{startLowStockJob();server.listen(port,()=>console.log(`SliceHouse API listening on ${port}`));}).catch(err=>{console.error('Startup failed:',err);process.exit(1);});
export {app,server};
